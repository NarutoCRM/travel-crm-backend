/*
|--------------------------------------------------------------------------
| CUSTOMER ACCEPTANCE
|--------------------------------------------------------------------------
*/

const acceptEmailController = async (
  req,
  res,
  next
) => {
  try {
    /*
     * Get real client IP.
     */
    const forwardedFor =
      req.headers["x-forwarded-for"];

    const ipAddress = forwardedFor
      ? String(forwardedFor)
          .split(",")[0]
          .trim()
      : req.ip;

    /*
     * Accept authorization.
     */
    const result =
      await acceptEmail({
        token:
          req.params.token,

        ipAddress,

        userAgent:
          req.get("user-agent") ||
          null,
      });

    return res.json({
      success: true,

      message:
        result.alreadyAccepted
          ? "This authorization was already completed."
          : "Authorization accepted successfully.",

      data: result,
    });

  } catch (error) {
    next(error);
  }
};

