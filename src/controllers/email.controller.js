import {
  sendEmail,
  getEmails,
  getEmailById,
  getLeadEmails,
  acceptEmail,
} from "../services/email.service.js";

/*
|--------------------------------------------------------------------------
| CREATE + SEND EMAIL
|--------------------------------------------------------------------------
*/

const createAndSendEmail = async (
  req,
  res,
  next
) => {
  try {
    const {
      leadId,
      subject,
      htmlBody,
      draft,
      recipientEmail,
      cardLast4,
    } = req.body;

    /*
     * IMPORTANT:
     *
     * sentById frontend se nahi liya ja raha.
     * JWT se authenticated user ka ID liya ja raha hai.
     */
    const result = await sendEmail({
      leadId: leadId || null,

      sentById: req.user.userId,

      subject,

      /*
       * Complete HTML generated by EmailBuilder.
       */
      htmlBody,

      draft,

      recipientEmail,

      /*
       * Only last 4 digits.
       * Full card number backend ko nahi bhejna.
       */
      cardLast4,
    });

    return res.status(201).json({
      success: true,

      message:
        "Email sent successfully. Waiting for customer authorization.",

      data: result,
    });

  } catch (error) {
    next(error);
  }
};

/*
|--------------------------------------------------------------------------
| LIST EMAILS
|--------------------------------------------------------------------------
*/

const listEmails = async (
  req,
  res,
  next
) => {
  try {
    const isSuperAdmin =
      req.user.role === "SUPER_ADMIN";

    const emails = await getEmails({
      /*
       * IMPORTANT:
       * JWT contains userId, not id.
       */
      userId: req.user.userId,

      isSuperAdmin,

      status:
        req.query.status,
    });

    return res.json({
      success: true,

      message:
        "Emails fetched successfully",

      data: emails,
    });

  } catch (error) {
    next(error);
  }
};

/*
|--------------------------------------------------------------------------
| GET SINGLE EMAIL
|--------------------------------------------------------------------------
*/

const getEmail = async (
  req,
  res,
  next
) => {
  try {
    const isSuperAdmin =
      req.user.role === "SUPER_ADMIN";

    const email =
      await getEmailById({
        emailId: req.params.id,

        /*
         * IMPORTANT:
         * Use userId from JWT.
         */
        userId: req.user.userId,

        isSuperAdmin,
      });

    return res.json({
      success: true,

      message:
        "Email fetched successfully",

      data: email,
    });

  } catch (error) {
    next(error);
  }
};

